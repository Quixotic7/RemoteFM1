// The v2 Move screen mockups' reference hashes: runs the design canvas's renderer (V2Screen.dc.html, every screen
// in S) and writes tests/move_v2_ref.h (FNV-1a over the 128 x 64 pixels, 0 / 1 a byte) and, with a second argument,
// each screen as a PBM in that folder. Usage: node move_v2_ref.mjs V2Screen.dc.html [pbm-dir]
import { readFileSync, writeFileSync } from "fs";
import { dirname, join } from "path";
import { fileURLToPath } from "url";
const html = readFileSync(process.argv[2], "utf8");
let js = html.split('<script type="text/x-dc" data-dc-script')[1];
js = js.slice(js.indexOf(">") + 1, js.lastIndexOf("</script>")).replace(/class Component[\s\S]*$/, "");
const { S, W, H } = new Function(js + "\nreturn { S, W, H };")();
const rows = [];
for (const n of Object.keys(S)) {
  const b = new Uint8Array(W * H);
  S[n](b);
  let h = 0x811c9dc5;
  for (const v of b) h = Math.imul(h ^ v, 0x01000193) >>> 0;
  rows.push(`    { "${n}", 0x${h.toString(16).padStart(8, "0")}u },`);
  if (process.argv[3]) {
    let s = `P1\n${W} ${H}\n`;
    for (let y = 0; y < H; y++) s += Array.from(b.slice(y * W, y * W + W)).join(" ") + "\n";
    writeFileSync(join(process.argv[3], `${n}.pbm`), s);
  }
}
const out = `/* generated by move_v2_ref.mjs from the design canvas's V2Screen.dc.html: do not edit */
static const struct { const char *name; uint32_t hash; } V2_REF[] = {
${rows.join("\n")}
};
`;
writeFileSync(join(dirname(fileURLToPath(import.meta.url)), "move_v2_ref.h"), out);
console.log(rows.length, "screens");
