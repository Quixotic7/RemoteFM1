"""The standalone screens' pixel font: Jersey 10 (OFL-1.1) as a 1-bit grid font, build/gen/sa_font.h.

  gen_pixfont.py --out build/gen/sa_font.h [--ttf PATH]

Jersey 10 (Sarah Cadigan-Fried, The Soft Type Project; third_party/jersey10/, OFL-1.1) is a pixel font: every point
of its outlines lies on a grid of 75 units (1,400 to the em), its capitals 10 grid pixels tall. So it is rasterised
once, a bit per grid pixel, and the firmware draws it at any whole scale n (each grid pixel an n x n block: the cap
height is 10 n device pixels), which keeps every size crisp and the whole font about 3 KB of flash.

Each glyph is 14 rows (grid y from 12 down to -2: row 12 sits on the baseline, rows 12..13 the descenders) of up to
16 columns (bit 0 the leftmost, at x0 grid pixels from the pen), and an advance. The characters: ASCII 32..126, then
the degree sign (U+00B0, index 95) and o-slash (U+00F8, 96). Rasterised with Pillow (the build's own dependency) at
8 device pixels a grid pixel, each grid cell read at its centre: the outlines are on the grid, so the reading is
exact whatever the hinting does with a fraction of a pixel.
"""
import argparse
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

GRID = 75                     # font units a grid pixel
UPM = 1400
ROWS = 14                     # grid y 12 .. -2
TOP = 12                      # rows above the baseline
S = 8                         # device pixels a grid pixel while rasterising
MARGIN = 3                    # grid pixels left and right of the pen, for overhangs
EXTRA = [0xB0, 0xF8]          # degree, o-slash (index 95, 96)


def glyph(font, ch):
    adv_px = font.getlength(ch)
    adv = int(round(adv_px / S))
    w = adv + 2 * MARGIN + 2
    img = Image.new("L", (w * S, (ROWS + 2) * S), 0)
    base = (TOP + 1) * S                      # the baseline, a grid row below the top
    ImageDraw.Draw(img).text((MARGIN * S, base), ch, font=font, fill=255, anchor="ls")
    px = img.load()
    cols = []
    rows = [0] * ROWS
    for gx in range(w):
        for r in range(ROWS):
            y = base - (TOP - r) * S + S // 2   # row r covers grid y [11 - r, 12 - r] above the baseline
            if px[gx * S + S // 2, y] >= 128:
                cols.append(gx)
                break
    if not cols:
        return adv, 0, 0, rows
    x_lo, x_hi = min(cols), max(cols)
    for r in range(ROWS):
        y = base - (TOP - r) * S + S // 2
        bits = 0
        for gx in range(x_lo, x_hi + 1):
            if px[gx * S + S // 2, y] >= 128:
                bits |= 1 << (gx - x_lo)
        rows[r] = bits
    # the top margin row (grid y 12..13) must be empty: nothing of these characters reaches it
    top = base - (TOP + 1) * S + S // 2
    for gx in range(w):
        assert px[gx * S + S // 2, top] < 128, f"{ch!r} rises above grid row 12"
    width = x_hi - x_lo + 1
    assert width <= 16, f"{ch!r} is {width} grid pixels wide"
    return adv, x_lo - MARGIN, width, rows


def main():
    here = Path(__file__).resolve().parent.parent
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--ttf", type=Path, default=here / "third_party/jersey10/Jersey10-Regular.ttf")
    a = ap.parse_args()
    font = ImageFont.truetype(str(a.ttf), size=S * UPM / GRID)
    chars = [chr(c) for c in range(32, 127)] + [chr(c) for c in EXTRA]
    gl = [glyph(font, ch) for ch in chars]
    out = ["/* SPDX-License-Identifier: MPL-2.0 AND OFL-1.1",
           " * Generated by firmware/tools/gen_pixfont.py from Jersey 10 (Copyright 2023 The Soft Type Project Authors,",
           " * SIL Open Font License 1.1: firmware/third_party/jersey10/OFL.txt). Do not edit. */",
           "#pragma once",
           "#include <stdint.h>",
           f"#define SA_PF_ROWS {ROWS}u                 /* rows a glyph: grid y 12 .. -2 */",
           f"#define SA_PF_TOP {TOP}u                   /* rows above the baseline */",
           "#define SA_PF_CAP 10u                    /* the capitals' height, grid pixels */",
           "#define SA_PF_XH 8u                      /* the lower case's */",
           f"#define SA_PF_N {len(chars)}u                    /* ASCII 32..126, then U+00B0 (95), U+00F8 (96) */",
           "typedef struct {",
           "    uint8_t adv;                         /* the advance, grid pixels */",
           "    int8_t x0;                           /* the first column's offset from the pen */",
           "    uint8_t w;                           /* columns */",
           "} sa_pf_glyph_t;",
           "static const sa_pf_glyph_t SA_PF_G[SA_PF_N] = {"]
    line = "   "
    for ch, (adv, x0, w, _) in zip(chars, gl):
        item = f" {{{adv}, {x0}, {w}}},"
        if len(line) + len(item) > 116:
            out.append(line)
            line = "   "
        line += item
    out.append(line)
    out.append("};")
    out.append("static const uint16_t SA_PF_BITS[SA_PF_N][SA_PF_ROWS] = {")
    for ch, (_, _, _, rows) in zip(chars, gl):
        name = ch if 32 < ord(ch) < 127 and ch not in "\\*/" else f"U+{ord(ch):04X}"
        out.append("    {" + ", ".join(f"0x{r:04X}" for r in rows) + "},   /* " + name + " */")
    out.append("};")
    text = "\n".join(out) + "\n"
    a.out.parent.mkdir(parents=True, exist_ok=True)
    if not a.out.exists() or a.out.read_text() != text:
        a.out.write_text(text)
    print(f"pixel font: Jersey 10, {len(chars)} glyphs, {len(chars) * (ROWS * 2 + 3)} B -> {a.out}")


if __name__ == "__main__":
    main()
