"""The standalone instrument's build options, as build/gen/sa_config.h (fm1.toml `gen`: every build).

  SA_BENCH=1 ./build.sh [--no-ble]     (or ./build.sh --bench): the bench build. At boot it measures FM6
                                       (firmware/sa/sa_bench.c) at 1, 8, 12 and 16 voices; SA_POLY 16
  ./build.sh                           SA_POLY 8, the bench only when asked over SysEx (1 and 8 voices)
"""
import argparse
import os
from pathlib import Path


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", type=Path, required=True)
    a = ap.parse_args()
    bench = os.environ.get("SA_BENCH") == "1"
    text = "\n".join([
        "/* SPDX-License-Identifier: MPL-2.0",
        " * Generated by firmware/tools/gen_sa_config.py (SA_BENCH=%s). Do not edit. */" % ("1" if bench else "0"),
        "#pragma once",
        "#ifndef SA_BENCH_BOOT",
        f"#define SA_BENCH_BOOT {int(bench)}               /* the FM6 bench runs at boot (firmware/sa/sa_bench.c) */",
        "#endif",
        "#ifndef SA_POLY",
        f"#define SA_POLY {16 if bench else 8}                     /* voices (firmware/sa/sa_synth.h) */",
        "#endif",
        ""])
    a.out.parent.mkdir(parents=True, exist_ok=True)
    if not a.out.exists() or a.out.read_text() != text:
        a.out.write_text(text)
    print(f"sa config: {a.out}" + (" (bench build)" if bench else ""))


if __name__ == "__main__":
    main()
