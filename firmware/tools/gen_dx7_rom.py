"""Yamaha's DX7 ROM cartridges, packed, as build/gen/dx7_rom.h (fm1.toml `gen`: every build).

  gen_dx7_rom.py --out build/gen/dx7_rom.h [--dir DIR]

Reads the eight 32-voice bulk dumps ROM1A..ROM4B (rom1a.syx .. rom4b.syx, any case) from DIR: --dir, else
$DX7_ROM_DIR, else the first `Presets/DX7-ROM` found beside this checkout or one of its parents (the owner keeps them in
ChoralRootFM1/Presets/DX7-ROM). Each must be a whole DX7 32-voice dump (F0 43 0n 09 20 00, 4,096 bytes of voice data,
its checksum, F7); the 32 packed voices (VMEM, 128 bytes each) go into the header as they are, with their names.

The voice data is Yamaha's (the rights stay with Yamaha). It is compiled into the firmware only: neither the .syx files
nor this header are ever committed or published (build/ is not in the repository; STANDALONE-PLAN.md). Without the
files the build goes on with no cartridge at all, and the instrument has only the DX7's INIT VOICE (it says so here).
"""
import argparse
import os
from pathlib import Path

BANKS = ["rom1a", "rom1b", "rom2a", "rom2b", "rom3a", "rom3b", "rom4a", "rom4b"]


def find_dir(arg):
    if arg:
        return Path(arg)
    if os.environ.get("DX7_ROM_DIR"):
        return Path(os.environ["DX7_ROM_DIR"])
    for p in Path(__file__).resolve().parents:
        d = p / "Presets" / "DX7-ROM"
        if d.is_dir():
            return d
    return None


def load(d, name):
    files = {f.name.lower(): f for f in d.iterdir()} if d and d.is_dir() else {}
    f = files.get(name + ".syx")
    if f is None:
        raise ValueError(f"{name}.syx not found")
    b = f.read_bytes()
    if len(b) != 4104 or b[:6] != bytes([0xF0, 0x43, b[2] & 0x0F, 0x09, 0x20, 0x00]) or b[-1] != 0xF7:
        raise ValueError(f"{f.name}: not a DX7 32-voice dump (F0 43 0n 09 20 00 .. F7, 4,104 bytes)")
    data = b[6:6 + 4096]
    if any(x & 0x80 for x in data) or (sum(data) + b[6 + 4096]) & 0x7F:
        raise ValueError(f"{f.name}: bad checksum or data")
    voices = [data[128 * k:128 * (k + 1)] for k in range(32)]
    names = [bytes(v[118:128]).decode("ascii", "replace") for v in voices]
    return voices, names


def c_str(s):
    return '"' + "".join(c if 32 <= ord(c) < 127 and c not in '"\\' else "?" for c in s) + '"'


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--dir")
    a = ap.parse_args()
    d = find_dir(a.dir)
    banks, why = [], ""
    try:
        for n in BANKS:
            banks.append((n.upper(), *load(d, n)))
    except (ValueError, OSError) as e:
        banks, why = [], str(e)
    out = ["/* Generated by firmware/tools/gen_dx7_rom.py. Do not edit, never commit: Yamaha's DX7 ROM voice data",
           " * (the rights stay with Yamaha), compiled into the firmware only. */",
           "#pragma once",
           "#include <stdint.h>",
           f"#define SA_ROM_NBANKS {len(banks)}u"]
    if banks:
        out.append("static const char SA_ROM_BANK[SA_ROM_NBANKS][6] = {" +
                   ", ".join(c_str(n) for n, _, _ in banks) + "};")
        out.append("static const uint8_t SA_ROM[SA_ROM_NBANKS][32][128] = {")
        for n, voices, names in banks:
            out.append(f"    {{   /* {n} */")
            for v, nm in zip(voices, names):
                out.append("        {" + ",".join(str(x) for x in v) + "},   /* " + nm.replace("*", "?") + " */")
            out.append("    },")
        out.append("};")
    text = "\n".join(out) + "\n"
    a.out.parent.mkdir(parents=True, exist_ok=True)
    if not a.out.exists() or a.out.read_text() != text:
        a.out.write_text(text)
    if banks:
        print(f"dx7 rom: {len(banks)} cartridges from {d} ({len(banks) * 32} voices, {len(banks) * 4096} B) -> {a.out}")
    else:
        print(f"dx7 rom: NO CARTRIDGES ({why}; DX7_ROM_DIR or --dir): the INIT VOICE only -> {a.out}")


if __name__ == "__main__":
    main()
